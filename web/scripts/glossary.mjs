async function getWikitext(page) {
  const url = new URL(Api);
  url.search = new URLSearchParams({
    action: "parse",
    page,
    prop: "wikitext",
    format: "json",
    formatversion: "2",
    redirects: "1",
  }).toString();

  const response = await fetch(url, { headers: { "user-agent": "genshin-schedule glossary script" } });
  const data = await response.json();

  if (data.error) {
    throw new Error(`${page}: ${data.error.info}`);
  }

  return data.parse.wikitext;
}

/** Returns the parameters of the first {{Other Languages}} template, e.g. { en: "Original Resin", ja: "天然樹脂" }. */
function parseOtherLanguages(wikitext) {
  const start = wikitext.indexOf("{{Other Languages");

  if (start < 0) {
    return;
  }

  // find the end of the template, which may contain other templates
  let depth = 0;
  let end = start;

  do {
    if (wikitext.startsWith("{{", end)) {
      depth++;
      end += 2;
    } else if (wikitext.startsWith("}}", end)) {
      depth--;
      end += 2;
    } else {
      end++;
    }
  } while (depth > 0 && end < wikitext.length);

  const params = {};

  for (const line of wikitext.slice(start, end).split("\n")) {
    const match = line.match(/^\|\s*([\w]+)\s*=(.*)$/);

    if (match) {
      params[match[1]] = match[2].trim();
    }
  }

  return params;
}

/** Removes wiki markup from a name, e.g. ruby text, tooltips and references. */
function clean(value) {
  return (
    value
      .replace(/<ref[^>]*>.*?<\/ref>|<ref[^>]*\/>/g, "")
      // {{Rubi|塵|じん|歌|か}} shows 塵歌 with readings above it
      .replace(/\{\{Rubi\|([^}]*)\}\}/g, (_, args) =>
        args
          .split("|")
          .filter((_, i) => i % 2 === 0)
          .join(""),
      )
      // {{tt|text|tooltip}}
      .replace(/\{\{tt\|([^|}]*)(\|[^}]*)?\}\}/g, "$1")
      .replace(/\{\{[^}]*\}\}/g, "")
      .replace(/\[\[(?:[^|\]]*\|)?([^\]]*)\]\]/g, "$1")
      .replace(/\/\//g, "")
      .replace(/'''?/g, "")
      .trim()
  );
}

const glossary = {
  $comment:
    "Official names of game terms in the game's languages, from the Genshin Impact Fandom wiki. Generated by `npm run glossary`; don't edit by hand. Translations should use these names.",
  terms: {},
};

for (const { key, page, note } of terms) {
  const params = parseOtherLanguages(await getWikitext(page));

  if (!params) {
    throw new Error(`${page}: no {{Other Languages}} template`);
  }

  // some pages list several names in numbered rows (1_en, 2_en, ...); the first row is the page's subject
  const prefix = "en" in params ? "" : "1_";
  const names = {};

  for (const [wiki, language] of Object.entries(languages)) {
    const value = params[prefix + wiki];

    if (value) {
      names[language] = clean(value);
    }
  }

  glossary.terms[key] = {
    source: `https://genshin-impact.fandom.com/wiki/${encodeURIComponent(page.replaceAll(" ", "_"))}`,
    ...(note && { note }),
    names,
  };

  console.log(`${key}: ${Object.keys(names).length} languages`);
}

await writeFile(Output, JSON.stringify(glossary, null, 2) + "\n");
console.log(`Wrote ${Output.pathname}`);
