// Downloads the official names of game terms used on the site, in all of the game's languages, from the
// Genshin Impact Fandom wiki, and saves them to messages/glossary.json for translators.
//
// Usage: npm run glossary
//
// Each term's wiki page has an {{Other Languages}} template listing its name in every language the game supports.
// Some terms have no page of their own; for those, a page whose name contains the term is used, with a note.
